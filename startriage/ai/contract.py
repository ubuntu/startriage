"""What a triaged bug ends up with: the result rendered in the report.

The host assembles an :class:`AgentResult` from the phases' hand-offs (see
:mod:`startriage.ai.phases`); the model never submits it directly.
"""

from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel, ConfigDict


class TriageStatus(StrEnum):
    """Status recommended for a bug (or for one series of it)."""

    invalid = "Invalid"  # not a bug, or not in Ubuntu
    incomplete = "Incomplete"  # more information needed from the reporter
    confirmed = "Confirmed"  # reproduced or clearly real, not yet analysed
    triaged = "Triaged"  # valid, analysed, ready for a developer
    fix_released = "Fix Released"  # already fixed in this series
    wont_fix = "Won't Fix"  # will not be fixed in this series
    duplicate = "Duplicate"  # duplicate of another report
    no_change = "no-change"  # leave as-is; needs a human


class Importance(StrEnum):
    undecided = "Undecided"
    critical = "Critical"
    high = "High"
    medium = "Medium"
    low = "Low"
    wishlist = "Wishlist"


class ProposedFixKind(StrEnum):
    """How a proposed fix should be interpreted."""

    none = "none"  # no fix proposed
    reference = "reference"  # value is a URL/commit pointing at an existing fix
    diff = "diff"  # value is a unified diff generated by the agent


class ProposedFix(BaseModel):
    model_config = ConfigDict(extra="forbid")

    kind: ProposedFixKind
    value: str = ""


class SRUCandidate(BaseModel):
    """A stable series that may want a backported fix."""

    model_config = ConfigDict(extra="ignore")

    series: str
    reason: str


class AgentResult(BaseModel):
    """One bug's triage result, as rendered in the report."""

    model_config = ConfigDict(extra="ignore")

    bug: str
    package: str = ""
    short_title: str = ""
    status: TriageStatus
    importance: Importance = Importance.undecided
    series: dict[str, TriageStatus] = {}
    tags: list[str] = []
    duplicate_of: str = ""
    analysis: str = ""
    suggested_comment: str = ""
    proposed_fix: ProposedFix = ProposedFix(kind=ProposedFixKind.none)
    # How the proposed fix applies per series, as the host checked it ("clean", "fails", ...).
    fix_applies: dict[str, str] = {}
    references: list[str] = []
    sru_candidates: list[SRUCandidate] = []
    upstream_suggestion: str = ""
